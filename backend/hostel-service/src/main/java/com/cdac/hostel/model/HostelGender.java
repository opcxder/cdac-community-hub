package com.cdac.hostel.model;

/**
 * Enumeration representing the gender restriction for a hostel.
 * Indicates whether the hostel is for boys only, girls only, or both.
 */
public enum HostelGender {
    /**
     * Hostel is for boys only
     */
    BOYS,
    
    /**
     * Hostel is for girls only
     */
    GIRLS,
    
    /**
     * Hostel accepts both boys and girls
     */
    BOTH
}
